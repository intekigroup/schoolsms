export type Vars = Record<string, string | number>

/** Looks up `key` in `locale`, falling back to English then to the key itself, and fills `{placeholders}`. */
export function t(key: string, locale: Locale = 'en', vars?: Vars): string {
  const entry = translations[key]
  let out = entry?.[locale] ?? entry?.en ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
  return out
}

export function getAllTranslations(locale: Locale): Record<string, string> {
  const result: Record<string, string> = {}
  for (const [key, val] of Object.entries(translations)) result[key] = val[locale] ?? key
  return result
}

/** Whether a key exists — for tests that guard against untranslated additions. */
export function hasKey(key: string) { return key in translations }
